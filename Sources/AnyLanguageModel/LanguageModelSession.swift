                rawContent: GeneratedContent,
                transcriptEntries: ArraySlice<Transcript.Entry> = [],
                usage: Usage = .init(
                    input: .init(totalTokenCount: 0, cachedTokenCount: 0),
                    output: .init(totalTokenCount: 0, reasoningTokenCount: 0)
                )
