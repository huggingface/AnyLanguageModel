    ) async throws -> Response<Content> where Content: Generable {
        try await wrapRespond { promptID in
            // Build segments from text and images
            var segments: [Transcript.Segment] = []
            if !prompt.isEmpty {
                segments.append(.text(.init(content: prompt)))
            }
            segments.append(contentsOf: images.map { .image($0) })

            // Add prompt to transcript
            let promptEntry = Transcript.Entry.prompt(
                Transcript.Prompt(
                    id: promptID,
                    segments: segments,
                    options: options,
                    responseFormat: type == String.self ? nil : .init(type: type)
                )
            )
            withMutation(keyPath: \.transcript) {
                state.withLock { $0.transcript.append(promptEntry) }
            }

            // Extract text content for the Prompt parameter
            let textPrompt = Prompt(prompt)

            let profiled = try await profiledResponse(options: options) {
                model,
                resolvedOptions,
                contextOptions in
                try await model.respond(
                    within: self,
                    to: textPrompt,
                    generating: type,
                    includeSchemaInPrompt: contextOptions.includeSchemaInPrompt
                        ?? includeSchemaInPrompt,
                    options: resolvedOptions
                )
            }
            let response = Self.representingNilExplicitly(
                in: profiled.response,
                responseFormat: type == String.self ? nil : .init(type: type)
            )

            recordUsage(response.usage)

            // Add response entry to transcript
            let textContent: String
            if case .string(let str) = response.rawContent.kind {
                textContent = str
            } else {
                textContent = response.rawContent.jsonString
            }

            let responseEntry = Transcript.Entry.response(
                Transcript.Response(
                    assetIDs: [],
                    segments: [.text(.init(content: textContent))],
                    providerMetadata: response.providerMetadata
                )
            )

            try await commitResponse(
                response,
                entry: responseEntry,
                prepared: profiled.prepared
            )

            return response
        }
    }

    /// Streams a text response to a prompt and an image.
    ///
    /// - Note: This API is exclusive to AnyLanguageModel
    ///   and will change to match Foundation Models 27 prompt attachments
    ///   in AnyLanguageModel 2.0.
    public func streamResponse(
        to prompt: String,
        image: Transcript.ImageSegment,
        options: GenerationOptions = GenerationOptions()
    ) -> sending ResponseStream<String> {
        streamResponse(
            to: prompt,
            images: [image],
            options: options
        )
    }

    /// Streams a text response to a prompt and images.
    ///
    /// - Note: This API is exclusive to AnyLanguageModel
    ///   and will change to match Foundation Models 27 prompt attachments
    ///   in AnyLanguageModel 2.0.
    public func streamResponse(
        to prompt: String,
        images: [Transcript.ImageSegment],
        options: GenerationOptions = GenerationOptions()
    ) -> sending ResponseStream<String> {
        streamResponse(
            to: prompt,
            images: images,
            generating: String.self,
            includeSchemaInPrompt: true,
            options: options
        )
    }

    /// Streams a response of the specified type to a prompt and an image.
    ///
    /// - Note: This API is exclusive to AnyLanguageModel
    ///   and will change to match Foundation Models 27 prompt attachments
    ///   in AnyLanguageModel 2.0.
    nonisolated public func streamResponse<Content>(
        to prompt: String,
        image: Transcript.ImageSegment,
        generating type: Content.Type = Content.self,
        includeSchemaInPrompt: Bool = true,
        options: GenerationOptions = GenerationOptions()
    ) -> sending ResponseStream<Content> where Content: Generable {
        streamResponse(
            to: prompt,
            images: [image],
            generating: type,
            includeSchemaInPrompt: includeSchemaInPrompt,
            options: options
        )
    }

    /// Streams a response of the specified type to a prompt and images.
    ///
    /// - Note: This API is exclusive to AnyLanguageModel
    ///   and will change to match Foundation Models 27 prompt attachments
    ///   in AnyLanguageModel 2.0.
    nonisolated public func streamResponse<Content>(
        to prompt: String,
        images: [Transcript.ImageSegment],
        generating type: Content.Type = Content.self,
        includeSchemaInPrompt: Bool = true,
        options: GenerationOptions = GenerationOptions()
    ) -> sending ResponseStream<Content> where Content: Generable {
        // Build segments from text and images
        var segments: [Transcript.Segment] = []
        if !prompt.isEmpty {
            segments.append(.text(.init(content: prompt)))
        }
        segments.append(contentsOf: images.map { .image($0) })

        // Create prompt entry that will be added when stream starts
        let promptEntry = Transcript.Entry.prompt(
            Transcript.Prompt(
                segments: segments,
                options: options,
                responseFormat: type == String.self ? nil : .init(type: type)
            )
        )
        withMutation(keyPath: \.transcript) {
            state.withLock { $0.transcript.append(promptEntry) }
        }

        // Extract text content for the Prompt parameter
        let textPrompt = Prompt(prompt)

        let upstream: ResponseStream<Content>
        let profileTracker: PreparedProfileRequestTracker?
        if dynamicProfile != nil {
            let tracker = PreparedProfileRequestTracker()
            profileTracker = tracker
            upstream = profileDispatchedStream(options: options, tracker: tracker) {
                model,
                resolvedOptions,
                contextOptions in
                model.streamResponse(
                    within: self,
                    to: textPrompt,
                    generating: type,
                    includeSchemaInPrompt: contextOptions.includeSchemaInPrompt
                        ?? includeSchemaInPrompt,
                    options: resolvedOptions
                )
            }
        } else {
            profileTracker = nil
            upstream = model.streamResponse(
                within: self,
                to: textPrompt,
                generating: type,
                includeSchemaInPrompt: includeSchemaInPrompt,
                options: options
            )
        }
        return wrapStream(
            upstream,
            promptEntry: promptEntry,
            profileTracker: profileTracker
        )
    }
}

