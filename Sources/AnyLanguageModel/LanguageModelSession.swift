extension LanguageModelSession {
    /// An asynchronous sequence of snapshots of a model response.
    public struct ResponseStream<Content>: Sendable where Content: Generable, Content.PartiallyGenerated: Sendable {
        private let fallbackSnapshot: Snapshot?
        private let streaming: AsyncThrowingStream<Snapshot, any Error>?

        /// Creates a response stream that yields a single snapshot.
        /// - Parameters:
        ///   - content: The complete response content.
        ///   - rawContent: The raw content produced by the model.
        ///   - usage: Provider-reported token usage.
        ///
        /// - Note: This initializer is exclusive to AnyLanguageModel.
        ///   It's public so that language models outside this module
        ///   can create response streams;
        ///   Foundation Models doesn't make it public.
        public init(
            content: Content,
            rawContent: GeneratedContent,
            usage: Usage = .init(
                input: .init(totalTokenCount: 0, cachedTokenCount: 0),
                output: .init(totalTokenCount: 0, reasoningTokenCount: 0)
            )
        ) {
            self.fallbackSnapshot = Snapshot(
                content: content.asPartiallyGenerated(),
                rawContent: rawContent,
                usage: usage
            )
            self.streaming = nil
        }

        /// Creates a response stream that yields snapshots from an async stream.
        /// - Parameter stream: The snapshot stream to relay.
        ///
        /// - Note: This initializer is exclusive to AnyLanguageModel.
        ///   It's public so that language models outside this module
        ///   can create response streams;
        ///   Foundation Models doesn't make it public.
        public init(stream: AsyncThrowingStream<Snapshot, any Error>) {
            // When streaming, snapshots arrive from the upstream sequence, so no fallback is required.
            self.fallbackSnapshot = nil
            self.streaming = stream
        }

        /// A snapshot of partially generated content and response metadata.
        public struct Snapshot: Sendable where Content.PartiallyGenerated: Sendable {
            /// The partially generated response content.
            public var content: Content.PartiallyGenerated

            /// The raw content produced so far by the model.
            public var rawContent: GeneratedContent

            /// Transcript entries (reasoning, tool calls and outputs) produced so far while streaming.
            /// Cumulative across tool rounds;
            /// empty for providers that don't stream reasoning or tool activity.
            ///
            /// - Note: This property is exclusive to AnyLanguageModel on OS 26.
            ///   It follows the Foundation Models 27 `ResponseStream.Snapshot.transcriptEntries` API,
            ///   so code that uses it ports to Foundation Models on OS 27.
            public var transcriptEntries: ArraySlice<Transcript.Entry>

            /// Provider-reported counts so far,
            /// with zero counts for values the provider does not report.
            ///
            /// - Note: This property is exclusive to AnyLanguageModel on OS 26.
            ///   It follows the Foundation Models 27 `ResponseStream.Snapshot.usage` API,
            ///   so code that uses it ports to Foundation Models on OS 27.
            public var usage: Usage

            internal var providerMetadata: [String: String]?

            /// Creates a snapshot from partially generated content and raw content.
            /// - Parameters:
            ///   - content: The partially generated content.
            ///   - rawContent: The raw content produced by the model.
            ///   - transcriptEntries: Transcript entries accumulated so far (reasoning/tool calls/outputs).
            ///   - usage: Provider-reported token usage so far.
            ///
            /// - Note: This initializer is exclusive to AnyLanguageModel.
            ///   It's public so that language models outside this module
            ///   can create snapshots;
            ///   Foundation Models doesn't make it public.
            public init(
                content: Content.PartiallyGenerated,
                rawContent: GeneratedContent,
                transcriptEntries: ArraySlice<Transcript.Entry> = [],
                usage: Usage = .init(
                    input: .init(totalTokenCount: 0, cachedTokenCount: 0),
                    output: .init(totalTokenCount: 0, reasoningTokenCount: 0)
                )
            ) {
                self.init(
                    content: content,
                    rawContent: rawContent,
                    transcriptEntries: transcriptEntries,
                    usage: usage,
                    providerMetadata: nil
                )
            }

            internal init(
                content: Content.PartiallyGenerated,
                rawContent: GeneratedContent,
                transcriptEntries: ArraySlice<Transcript.Entry> = [],
                usage: Usage = .init(
                    input: .init(totalTokenCount: 0, cachedTokenCount: 0),
                    output: .init(totalTokenCount: 0, reasoningTokenCount: 0)
                ),
                providerMetadata: [String: String]?
            ) {
                self.content = content
                self.rawContent = rawContent
                self.transcriptEntries = transcriptEntries
                self.usage = usage
                self.providerMetadata = providerMetadata
            }
        }
    }
}

extension LanguageModelSession.ResponseStream: AsyncSequence {
    public typealias Element = Snapshot

    public struct AsyncIterator: AsyncIteratorProtocol {
        private var hasYielded = false
        private let fallbackSnapshot: Snapshot?
        private var streamIterator: AsyncThrowingStream<Snapshot, any Error>.AsyncIterator?
        private let useStream: Bool

        init(fallbackSnapshot: Snapshot?, stream: AsyncThrowingStream<Snapshot, any Error>?) {
            self.fallbackSnapshot = fallbackSnapshot
            self.streamIterator = stream?.makeAsyncIterator()
            self.useStream = stream != nil
        }

        public mutating func next() async throws -> Snapshot? {
            if useStream {
                if var iterator = streamIterator {
                    if let value = try await iterator.next() {
                        // store back the advanced iterator
                        streamIterator = iterator
                        return value
                    }
                    streamIterator = iterator
                }
                return nil
            } else {
                guard !hasYielded, let fallbackSnapshot else { return nil }
                hasYielded = true
                return fallbackSnapshot
            }
        }

        public typealias Element = Snapshot
    }

    public func makeAsyncIterator() -> AsyncIterator {
        return AsyncIterator(fallbackSnapshot: fallbackSnapshot, stream: streaming)
    }

    nonisolated public func collect() async throws -> sending LanguageModelSession.Response<Content> {
        if let streaming {
            var last: Snapshot?
            for try await snapshot in streaming {
                last = snapshot
            }
            if let last {
                // Attempt to materialize a concrete Content from the last snapshot
                let finalContent: Content
                if let concrete = last.content as? Content {
                    finalContent = concrete
                } else {
                    finalContent = try Content(last.rawContent)
                }
                return LanguageModelSession.Response(
                    content: finalContent,
                    rawContent: last.rawContent,
                    transcriptEntries: last.transcriptEntries,
                    usage: last.usage,
                    providerMetadata: last.providerMetadata
                )
            }
        }

        if let fallbackSnapshot {
            let finalContent: Content
            if let concrete = fallbackSnapshot.content as? Content {
                finalContent = concrete
            } else {
                finalContent = try Content(fallbackSnapshot.rawContent)
            }
            return LanguageModelSession.Response(
                content: finalContent,
                rawContent: fallbackSnapshot.rawContent,
                transcriptEntries: fallbackSnapshot.transcriptEntries,
                usage: fallbackSnapshot.usage,
                providerMetadata: fallbackSnapshot.providerMetadata
            )
        }

        throw ResponseStreamError.noSnapshots
    }
}

private enum ResponseStreamError: Error, LocalizedError {
    case noSnapshots

    var errorDescription: String? {
        switch self {
        case .noSnapshots:
            return "The response stream ended without producing a snapshot."
        }
    }
}

