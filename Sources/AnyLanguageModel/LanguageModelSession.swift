    // The prompt is the only entry committed before a request succeeds. Checkpoints and
    // the final response commit atomically at completion, so rollback owns only this ID.
    nonisolated private func removePrompt(id: String) {
        withTranscriptMutation {
            state.withLock { state in
                state.transcript = Transcript(entries: state.transcript.filter { $0.id != id })
            }
        }
    }

    nonisolated private func wrapRespond<T>(
        profileTracker: PreparedProfileRequestTracker? = nil,
        _ operation: (String) async throws -> T
    ) async throws -> T {
        let promptID = UUID().uuidString
        beginResponding()
        do {
            // A profile callback that waits for this request
            // lets the request's callbacks, and other requests' callbacks, run until it ends.
            let result = try await ProfileActionSerializer.withPermitsReleased {
                try await operation(promptID)
            }
            endResponding()
            return result
        } catch {
            let policy: TranscriptErrorHandlingPolicy?
            if let prepared = profileTracker?.prepared {
                policy = prepared.context.transcriptErrorHandlingPolicy
            } else {
                policy = transcriptErrorHandlingPolicy
            }
            if policy == .revertTranscript {
                removePrompt(id: promptID)
            }
            endResponding()
            throw error
        }
    }

    /// Returns the response with a `null` value for each omitted optional property
    /// when the response format's schema represents `nil` explicitly.
    nonisolated private static func representingNilExplicitly<Content>(
        in response: Response<Content>,
        responseFormat: Transcript.ResponseFormat?
    ) -> Response<Content> where Content: Generable {
        guard let responseFormat else { return response }
        let rawContent = responseFormat.schema.representingNilExplicitly(in: response.rawContent)
        guard rawContent != response.rawContent else { return response }
        return Response(
            // Schema-based responses return the generated content itself.
            content: (rawContent as? Content) ?? response.content,
            rawContent: rawContent,
            transcriptEntries: response.transcriptEntries,
            requests: response.requests,
            providerMetadata: response.providerMetadata
        )
    }

    nonisolated private func wrapStream<Content>(
        _ upstream: sending ResponseStream<Content>,
        promptEntry: Transcript.Entry,
        profileTracker: PreparedProfileRequestTracker? = nil,
        counted: CountedRequestsUsage
    ) -> ResponseStream<Content> where Content: Generable, Content.PartiallyGenerated: Sendable {
        let session = self
        let relay = AsyncThrowingStream<ResponseStream<Content>.Snapshot, any Error> { continuation in
            let stream = upstream
            let relayID = UUID()
            // Publish the task under the same lock used by completion removal, so a
            // fast relay cannot finish before registration and leave a stale handle.
            let task = session.responseRelays.withLock { relays in
                let task = Task {
                    defer { session.responseRelays.withLock { _ = $0.removeValue(forKey: relayID) } }
                    session.beginResponding()
                    var lastSnapshot: ResponseStream<Content>.Snapshot?
                    var committedEntries = AppendedTranscriptEntries.none
                    do {
                        for try await snapshot in stream {
                            lastSnapshot = snapshot
                            counted.count(
                                snapshot.requests,
                                prepaid: snapshot.prepaid,
                                unprepaidUsage: snapshot.unprepaidUsage
                            )
                            continuation.yield(snapshot)
                        }

                        // AsyncThrowingStream may end normally when its task is cancelled.
                        // A partial snapshot must not become a completed transcript response.
                        try Task.checkCancellation()

                        // Commit the response to the transcript
                        // before the stream reports completion,
                        // so a caller that drains the stream
                        // and starts the next turn sees the full history.
                        guard let lastSnapshot else {
                            throw ResponseStreamError.noSnapshots
                        }
                        // Fill in `null` for omitted optional properties when the schema asks for it,
                        // and yield the result so that consumers and `collect()` see it.
                        var rawContent = lastSnapshot.rawContent
                        if case .prompt(let prompt) = promptEntry, let responseFormat = prompt.responseFormat {
                            rawContent = responseFormat.schema.representingNilExplicitly(in: rawContent)
                        }
                        if rawContent != lastSnapshot.rawContent {
                            continuation.yield(
                                ResponseStream<Content>.Snapshot(
                                    content: (try? Content.PartiallyGenerated(rawContent)) ?? lastSnapshot.content,
                                    rawContent: rawContent,
                                    transcriptEntries: lastSnapshot.transcriptEntries,
                                    requests: lastSnapshot.requests,
                                    providerMetadata: lastSnapshot.providerMetadata
                                )
                            )
                        }

                        // Extract text content from the generated content
                        let textContent: String
                        if case .string(let str) = rawContent.kind {
                            textContent = str
                        } else {
                            textContent = rawContent.jsonString
                        }

                        let responseEntry = Transcript.Entry.response(
                            Transcript.Response(
                                assetIDs: [],
                                segments: [.text(.init(content: textContent))],
                                providerMetadata: lastSnapshot.providerMetadata
                            )
                        )
                        var committed: HistorySnapshot?
                        committedEntries = session.withTranscriptMutation {
                            session.state.withLock { state in
                                guard state.transcript.contains(where: { $0.id == promptEntry.id }) else {
                                    return .none
                                }
                                let appended = state.appendResponse(
                                    Array(lastSnapshot.transcriptEntries) + [responseEntry]
                                )
                                committed = HistorySnapshot(state)
                                return appended
                            }
                        }
                        if !committedEntries.isEmpty, let prepared = profileTracker?.prepared, let committed {
                            let context = prepared.context.withCanonicalTranscript(
                                committed.entries,
                                version: committed.version
                            )
                            try await session.profileDidProduceEntries(
                                Array(lastSnapshot.transcriptEntries) + [responseEntry],
                                requestContext: context,
                                currentRoundEntries: []
                            )
                            session.lastResponseModel.withLock { $0 = prepared.context.model }
                        }
                        session.endResponding()
                        continuation.finish()
                    } catch {
                        if let stopped = error as? ToolExecutionStopped {
                            counted.count(stopped.requests, prepaid: nil)
                        }
                        session.withTranscriptMutation {
                            session.state.withLock { state in
                                state.removeEntries(committedEntries)
                                guard state.transcript.contains(where: { $0.id == promptEntry.id }) else { return }
                                let policy: TranscriptErrorHandlingPolicy?
                                if let prepared = profileTracker?.prepared {
                                    policy = prepared.context.transcriptErrorHandlingPolicy
                                } else {
                                    policy = state.transcriptErrorHandlingPolicy
                                }
                                if policy == .preserveTranscript {
                                    state.transcript.append(contentsOf: lastSnapshot?.transcriptEntries ?? [])
                                } else if policy == .revertTranscript {
                                    state.transcript = Transcript(
                                        entries: state.transcript.filter { $0.id != promptEntry.id }
                                    )
                                }
                            }
                        }
                        session.endResponding()
                        continuation.finish(throwing: error)
                    }
                }
                relays[relayID] = task
                return task
            }
            continuation.onTermination = { termination in
                if case .cancelled = termination {
                    task.cancel()
                }
            }
        }
        return ResponseStream(stream: relay)
    }

    /// Token usage reported by the model for a response.
    ///
    /// Matches the token-usage API in Foundation Models 27.
    /// Counts default to zero when the provider does not report them.
    ///
    /// - Note: This API is exclusive to AnyLanguageModel on OS 26.
    ///   It follows the Foundation Models 27 `Usage` API,
    ///   so code that uses it ports to Foundation Models on OS 27.
    ///   The `Codable` and `Equatable` conformances are exclusive to AnyLanguageModel;
    ///   Foundation Models 27 doesn't provide them.
    public struct Usage: Sendable, Equatable, Codable {
        /// Token counts for the input submitted to the model.
        public struct Input: Sendable, Equatable, Codable {
            /// The number of input tokens reported by the provider.
            public var totalTokenCount: Int

            /// The number of input tokens read from the provider's cache.
            public var cachedTokenCount: Int

            /// Creates input token counts.
            ///
            /// - Parameters:
            ///   - totalTokenCount: The reported input token count.
            ///   - cachedTokenCount: The reported count of input tokens read from cache.
            public init(totalTokenCount: Int, cachedTokenCount: Int) {
                self.totalTokenCount = totalTokenCount
                self.cachedTokenCount = cachedTokenCount
            }
        }

        /// Token counts for the output produced by the model.
        public struct Output: Sendable, Equatable, Codable {
            /// The number of output tokens reported by the provider.
            public var totalTokenCount: Int

            /// The number of reasoning tokens reported by the provider.
            public var reasoningTokenCount: Int

            /// Creates output token counts.
            ///
            /// - Parameters:
            ///   - totalTokenCount: The reported output token count.
            ///   - reasoningTokenCount: The reported reasoning token count.
            public init(totalTokenCount: Int, reasoningTokenCount: Int) {
                self.totalTokenCount = totalTokenCount
                self.reasoningTokenCount = reasoningTokenCount
            }
        }

        /// The token counts reported for the model's input.
        public var input: Input

        /// The token counts reported for the model's output.
        public var output: Output

        /// Additional usage statistics supplied by the model.
        public var metadata: [String: GeneratedContent]

        /// The sum of the input and output token counts.
        public var totalTokenCount: Int {
            input.totalTokenCount + output.totalTokenCount
        }

        /// Creates usage from input and output token counts.
        ///
        /// - Parameters:
        ///   - input: The input token counts.
        ///   - output: The output token counts.
        ///   - metadata: Additional usage statistics,
        ///     converted to generated content for storage.
        public init(
            input: Input,
            output: Output,
            metadata: [String: any ConvertibleToGeneratedContent] = [:]
        ) {
            self.input = input
            self.output = output
            self.metadata = metadata.mapValues { $0.generatedContent }
        }

        static let zero = Self(
            input: .init(totalTokenCount: 0, cachedTokenCount: 0),
            output: .init(totalTokenCount: 0, reasoningTokenCount: 0)
        )

        /// Accumulates counts across responses;
        /// the latest value wins for each metadata key.
        mutating func add(_ other: Self) {
            input.totalTokenCount += other.input.totalTokenCount
            input.cachedTokenCount += other.input.cachedTokenCount
            output.totalTokenCount += other.output.totalTokenCount
            output.reasoningTokenCount += other.output.reasoningTokenCount
            metadata.merge(other.metadata) { _, latest in latest }
        }

        /// The counts of `self` that aren't in `other`, which `self` adds up with others.
        /// A count `other` reports past `self`'s, read later, is none.
        func subtracting(_ other: Self) -> Self {
            Self(
                input: .init(
                    totalTokenCount: max(0, input.totalTokenCount - other.input.totalTokenCount),
                    cachedTokenCount: max(0, input.cachedTokenCount - other.input.cachedTokenCount)
                ),
                output: .init(
                    totalTokenCount: max(0, output.totalTokenCount - other.output.totalTokenCount),
                    reasoningTokenCount: max(0, output.reasoningTokenCount - other.output.reasoningTokenCount)
                ),
                metadata: metadata
            )
        }

        /// Returns counts not yet accounted for in this stream,
        /// retaining the highest reported count for each field
        /// and returning only new or changed metadata keys.
        func increment(since previous: inout Self) -> Self {
            func increase(_ count: Int, _ highest: inout Int) -> Int {
                let delta = max(0, count - highest)
                highest = max(highest, count)
                return delta
            }
            let changedMetadata = metadata.filter { previous.metadata[$0.key] != $0.value }
            previous.metadata.merge(changedMetadata) { _, latest in latest }
            return Self(
                input: .init(
                    totalTokenCount: increase(input.totalTokenCount, &previous.input.totalTokenCount),
                    cachedTokenCount: increase(input.cachedTokenCount, &previous.input.cachedTokenCount)
                ),
                output: .init(
                    totalTokenCount: increase(output.totalTokenCount, &previous.output.totalTokenCount),
                    reasoningTokenCount: increase(output.reasoningTokenCount, &previous.output.reasoningTokenCount)
                ),
                metadata: changedMetadata
            )
        }
    }

    /// A model response containing generated content and associated metadata.
    public struct Response<Content>: Sendable where Content: Generable, Content: Sendable {
        /// The decoded response content.
        public let content: Content

        /// The raw content produced by the model.
        public let rawContent: GeneratedContent

        /// The transcript entries associated with the response.
        public let transcriptEntries: ArraySlice<Transcript.Entry>

        /// Provider-reported token usage of the response's final request,
        /// with zero counts for values the provider does not report.
        ///
        /// A response that calls tools makes a request for each round,
        /// each with the conversation so far.
        /// As in Foundation Models, this is the final request's usage,
        /// and the session's ``LanguageModelSession/usage`` counts every request.
        ///
        /// - Note: This property is exclusive to AnyLanguageModel on OS 26.
        ///   It follows the Foundation Models 27 `Response.usage` API,
        ///   so code that uses it ports to Foundation Models on OS 27.
        public var usage: Usage { requests.final }

        /// The usage of each of the response's requests.
        internal let requests: RequestsUsage

        internal let providerMetadata: [String: String]?

        /// Creates a response value from generated content and transcript entries.
        /// - Parameters:
        ///   - content: The decoded response content.
        ///   - rawContent: The raw content produced by the model.
        ///   - transcriptEntries: Transcript entries associated with the response.
        ///   - usage: Provider-reported token usage of the response's final request.
        ///
        /// - Note: This initializer is exclusive to AnyLanguageModel.
        ///   It's public so that language models outside this module
        ///   can create responses;
        ///   Foundation Models doesn't make it public.
        public init(
            content: Content,
            rawContent: GeneratedContent,
            transcriptEntries: ArraySlice<Transcript.Entry>,
            usage: Usage = .init(
                input: .init(totalTokenCount: 0, cachedTokenCount: 0),
                output: .init(totalTokenCount: 0, reasoningTokenCount: 0)
            )
        ) {
            self.init(
                content: content,
                rawContent: rawContent,
                transcriptEntries: transcriptEntries,
                requests: RequestsUsage(final: usage)
            )
        }

        internal init(
            content: Content,
            rawContent: GeneratedContent,
            transcriptEntries: ArraySlice<Transcript.Entry>,
            requests: RequestsUsage,
            providerMetadata: [String: String]? = nil
        ) {
            self.content = content
            self.rawContent = rawContent
            self.transcriptEntries = transcriptEntries
            self.requests = requests
            self.providerMetadata = providerMetadata
        }
    }

